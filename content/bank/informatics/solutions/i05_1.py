"""Эталонное решение: информатика №5, задача 1 (стартовый банк, ИИ)."""


def R(n):
    b = bin(n)[2:]
    b += "0" if b.count("1") % 2 == 0 else "11"
    return int(b, 2)


# R растёт вместе с N (дописывается 1–2 цифры), поэтому достаточно N до 1000.
print(min(R(n) for n in range(1, 1000) if R(n) > 100))
