s = "1" * 70
while "111" in s or "22" in s:
    if "111" in s:  # noqa: SIM108 — повторяем структуру программы Редактора
        s = s.replace("111", "2", 1)  # заменить(v, w) меняет первое вхождение v
    else:
        s = s.replace("22", "1", 1)
print(s)
